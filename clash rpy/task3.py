a = int(input("Введіть перше число: "))
b = int(input("Введіть друге число: "))

summa = a + b
riznytsia = a - b
dobutok = a * b
chastka = a / b
tsila_chastyna = a // b
ostacha = a % b
stepin = a ** b

print(a, "+", b, "=", summa)
print(a, "-", b, "=", riznytsia)
print(a, "*", b, "=", dobutok)
print(a, "/", b, "=", chastka)
print(a, "//", b, "=", tsila_chastyna)
print(a, "%", b, "=", ostacha)
print(a, "**", b, "=", stepin)